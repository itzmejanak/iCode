package dev.icode.mobile.domain

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/** What first bytes say a file is (docs/workspaces-and-files.md): each format by its own signature, and text by none. */
class FileSignaturesTest {
    private fun bytes(vararg parts: Any): ByteArray = parts.flatMap { part ->
        when (part) {
            is String -> part.toByteArray(Charsets.ISO_8859_1).toList()
            is Int -> listOf(part.toByte())
            else -> error("strings and bytes")
        }
    }.toByteArray()

    /** [packet]-byte packets, the sync byte [offset] into each. */
    private fun stream(packet: Int, offset: Int) = ByteArray(FileTypes.HEAD_BYTES).also { head ->
        generateSequence(offset) { it + packet }.takeWhile { it < head.size }.forEach { head[it] = 0x47 }
    }

    @Test fun `a transport stream, as broadcast and as Blu-ray and AVCHD write it`() {
        assertEquals(FileTypes.Video, FileSignatures.of(stream(188, 0)))
        assertEquals(FileTypes.Video, FileSignatures.of(stream(192, 4)))
        // One "G" begins many a text: three packets are needed.
        assertNull(FileSignatures.of("Generated by the compiler; do not edit.\n".toByteArray()))
        assertNull(FileSignatures.of(ByteArray(200).also { it[0] = 0x47; it[188] = 0x47 }))
    }

    @Test fun `pictures, videos and sounds by their own signatures`() {
        mapOf(
            bytes(0x89, "PNG", 0x0D, 0x0A, 0x1A, 0x0A) to FileTypes.Image,
            bytes(0xFF, 0xD8, 0xFF, 0xE0) to FileTypes.Image,
            bytes("GIF89a", 1, 0) to FileTypes.Image,
            bytes("RIFF", 0, 0, 0, 0, "WEBP") to FileTypes.Image,
            bytes(0, 0, 0, 0x18, "ftypheic") to FileTypes.Image,
            bytes(0, 0, 0, 0x1C, "ftypavif") to FileTypes.Image,
            bytes(0, 0, 0, 0x18, "ftypisom") to FileTypes.Video,
            bytes(0, 0, 0, 0x14, "ftypqt  ") to FileTypes.Video,
            bytes(0, 0, 0, 0x20, "ftypM4A ") to FileTypes.Audio,
            bytes(0x1A, 0x45, 0xDF, 0xA3) to FileTypes.Video,
            bytes("RIFF", 0, 0, 0, 0, "AVI ") to FileTypes.Video,
            bytes("RIFF", 0, 0, 0, 0, "WAVE") to FileTypes.Audio,
            bytes("OggS", 0, 2) to FileTypes.Audio,
            bytes("fLaC", 0, 0, 0, 0x22) to FileTypes.Audio,
            bytes("ID3", 4, 0, 0) to FileTypes.Audio,
            bytes(0xFF, 0xFB, 0x90, 0x64) to FileTypes.Audio,
            bytes("MThd", 0, 0, 0, 6) to FileTypes.Audio,
        ).forEach { (head, type) -> assertEquals(head.take(12).toString(), type, FileSignatures.of(head)) }
    }

    @Test fun `documents, archives and other bytes`() {
        mapOf(
            bytes("%PDF-1.7") to FileTypes.Pdf,
            bytes("PK", 3, 4) to FileTypes.Archive,
            bytes(0x1F, 0x8B, 8) to FileTypes.Archive,
            bytes("7z", 0xBC, 0xAF, 0x27, 0x1C) to FileTypes.Archive,
            bytes("Rar!", 0x1A, 0x07, 0) to FileTypes.Archive,
            bytes("BZh91AY&SY") to FileTypes.Archive,
            bytes(0x7F, "ELF", 2) to FileTypes.Executable,
            bytes(0, "asm", 1, 0, 0, 0) to FileTypes.Executable,
            bytes("SQLite format 3", 0) to FileTypes.Database,
            bytes("wOF2", 0, 1, 0, 0) to FileTypes.Font,
        ).forEach { (head, type) -> assertEquals(String(head, Charsets.ISO_8859_1), type, FileSignatures.of(head)) }
        val tar = ByteArray(FileTypes.HEAD_BYTES).also { "ustar".forEachIndexed { at, c -> it[257 + at] = c.code.toByte() } }
        assertEquals(FileTypes.Archive, FileSignatures.of(tar))
    }

    @Test fun `text that begins as a signature does is still text`() {
        listOf(
            "OTTO said so.", "OggS is a word", "ID3 tags", "MThd", "BZh", "dex\nexplained", "BM 2024 report", "%PDF",
        ).forEach { assertNull(it, FileSignatures.of(it.toByteArray())) }
        // UTF-16 text begins FF FE: not an MP3 frame.
        assertNull(FileSignatures.of(bytes(0xFF, 0xFE, 'h'.code, 0)))
        assertNull(FileSignatures.of(ByteArray(0)))
    }
}
